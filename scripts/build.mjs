// Bundles the TypeScript source in src/ into the classic browser script app.js.
// The output is a single IIFE so index.html keeps working from file:// and GitHub Pages.
// Usage: node scripts/build.mjs [--watch]
import * as esbuild from "esbuild";

const options = {
  entryPoints: ["src/main.ts"],
  bundle: true,
  format: "iife",
  target: "es2020",
  outfile: "app.js",
  banner: {
    js: '"use strict";\n// Generated by scripts/build.mjs from src/. Edit the TypeScript source, not this file.',
  },
  logLevel: "info",
};

if (process.argv.includes("--watch")) {
  const context = await esbuild.context(options);
  await context.watch();
} else {
  await esbuild.build(options);
}
